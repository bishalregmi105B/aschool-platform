const List<String> _bsMonthsEn = [
  'Baisakh','Jestha','Ashadh','Shrawan','Bhadra','Ashwin',
  'Kartik','Mangsir','Poush','Magh','Falgun','Chaitra',
];

// BS epoch: 2000/01/01 BS = 1943-04-14 AD
final DateTime _bsEpochAd = DateTime(1943, 4, 14);

/// Convert an AD [DateTime] to a BS date string "D Month YYYY BS"
String adToBsString(DateTime ad) {
  int remaining = ad.difference(_bsEpochAd).inDays;

  for (int y = 2000; y <= 2090; y++) {
    final months = _bsData[y];
    if (months == null) break;
    for (int m = 0; m < 12; m++) {
      if (remaining < months[m]) {
        final day = remaining + 1;
        return '$day ${_bsMonthsEn[m]} $y';
      }
      remaining -= months[m];
    }
  }
  // Fallback
  return '${ad.year}-${ad.month.toString().padLeft(2,'0')}-${ad.day.toString().padLeft(2,'0')}';
}

/// Displays Nepali (BS) date with optional AD date below it
class NepaliDateDisplay extends StatelessWidget {
  final DateTime? date;
  final bool showAd;
  final TextStyle? style;
  final TextStyle? adStyle;

  const NepaliDateDisplay({
    super.key,
    this.date,
    this.showAd = false,
    this.style,
    this.adStyle,
  });

  @override
  Widget build(BuildContext context) {
    final d = date ?? DateTime.now();
    final bsStr = adToBsString(d);
    final adStr =
        '${d.year}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      mainAxisSize: MainAxisSize.min,
      children: [
        Text(bsStr, style: style ?? Theme.of(context).textTheme.bodyMedium),
        if (showAd)
          Text(
            adStr,
            style: adStyle ??
                Theme.of(context)
                    .textTheme
                    .bodySmall
                    ?.copyWith(color: Colors.grey[600]),
          ),
      ],
    );
  }
}
