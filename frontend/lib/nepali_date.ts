const BS_EPOCH_AD = new Date(1943, 3, 14); // April 14 1943

function daysBetween(a: Date, b: Date): number {
  const ms = b.getTime() - a.getTime();
  return Math.floor(ms / 86400000);
}

export interface BSDate { year: number; month: number; day: number }

export function adToBS(adDate: Date | string): BSDate {
  // Handle both date-only "YYYY-MM-DD" and full ISO datetime "YYYY-MM-DDT..."
  const d =
    typeof adDate === "string"
      ? new Date(adDate.includes("T") ? adDate : adDate + "T00:00:00")
      : adDate;
  let remaining = daysBetween(BS_EPOCH_AD, d);
  let bsYear = 2000;
  let bsMonth = 1;
  let bsDay = 1;

  outer: for (let y = 2000; y <= 2090; y++) {
    const months = BS_DATA[y];
    if (!months) break;
    for (let m = 0; m < 12; m++) {
      if (remaining < months[m]) {
        bsYear = y;
        bsMonth = m + 1;
        bsDay = remaining + 1;
        break outer;
      }
      remaining -= months[m];
    }
  }
  return { year: bsYear, month: bsMonth, day: bsDay };
}

export function bsToAD(bs: BSDate): Date {
  let days = 0;
  for (let y = 2000; y < bs.year; y++) {
    const months = BS_DATA[y];
    if (!months) break;
    days += months.reduce((a, b) => a + b, 0);
  }
  const months = BS_DATA[bs.year];
  if (months) {
    for (let m = 0; m < bs.month - 1; m++) days += months[m];
  }
  days += bs.day - 1;
  const result = new Date(BS_EPOCH_AD);
  result.setDate(result.getDate() + days);
  return result;
}

// "2026-05-15" → { year:2083, month:2, day:2 }
export function adStringToBS(adStr: string): BSDate {
  return adToBS(adStr);
}

// BSDate → "2083-02-02"
export function bsToString(bs: BSDate): string {
  return `${bs.year}-${String(bs.month).padStart(2, "0")}-${String(bs.day).padStart(2, "0")}`;
}

// BSDate → "2 Jestha 2083"
export function formatBSDate(bs: BSDate | string | null | undefined, lang: "en" | "ne" = "en"): string {
  if (!bs) return "N/A";
  const b: BSDate = typeof bs === "string" ? adStringToBS(bs) : bs;
  const months = lang === "ne" ? BS_MONTHS_NE : BS_MONTHS;
  return `${b.day} ${months[b.month - 1]} ${b.year}`;
}

// Today as AD string "YYYY-MM-DD"
export function todayAD(): string {
  return new Date().toISOString().split("T")[0];
}

// Today as BS string "YYYY-MM-DD"
export function todayBS(): string {
  return bsToString(adToBS(new Date()));
}

// Convert any AD date string for display as BS
export function displayBS(adDateStr: string | null | undefined, lang: "en" | "ne" = "en"): string {
  if (!adDateStr) return "N/A";
  try {
    return formatBSDate(adToBS(adDateStr), lang);
  } catch {
    return adDateStr;
  }
}

// ── Legacy: format existing BS strings "2082-01-15" → "15 Baisakh 2082" ────
export function formatNepaliDate(bsDateStr: string | null | undefined): string {
  if (!bsDateStr) return "N/A";
  const parts = bsDateStr.split("-");
  if (parts.length !== 3) return bsDateStr;
  const year = parts[0];
  const monthIdx = parseInt(parts[1], 10) - 1;
  const day = parseInt(parts[2], 10);
  if (monthIdx >= 0 && monthIdx < 12) {
    return `${day} ${BS_MONTHS[monthIdx]} ${year}`;
  }
  return bsDateStr;
}
